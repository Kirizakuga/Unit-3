#!/usr/bin/env python3
"""Unit-3 settings backend for the Control Center "System" card.

    unit3-settings.py state              print current settings + live system state as JSON
    unit3-settings.py set <key> <value>  change one setting, save it, and apply it

Keys:
    display.primary <output>            screen that gets workspace 1 and the cursor
    display.side <left|right>           which side of the laptop the external screen(s) sit
    display.rate.<output> <hz>          refresh rate, chosen from the modes the screen supports
    display.wideColor <true|false>      wide color gamut (default off; only useful with 10-bit output)
    lock.idle <minutes>                 0 = never lock when idle
    lock.sleep <true|false>             lock before suspend
    power.profile <name>                powerprofilesctl profile
    power.brightness <percent>          laptop backlight, 5-100
    shell.player <true|false>           show the music player
    shell.playerBg <true|false>         dark background behind the player
    shell.companions <true|false>       show the companions

Saved settings live in ~/.config/quickshell/settings/user.json (Settings.qml watches it).
Display settings are written to ~/.config/hypr/monitors.lua, lock settings to
~/.config/hypr/hypridle.conf.
"""
import json
import os
import re
import subprocess
import sys

HOME = os.path.expanduser("~")
STORE = os.path.join(HOME, ".config/quickshell/settings/user.json")
MONITORS_LUA = os.path.join(HOME, ".config/hypr/monitors.lua")
HYPRIDLE = os.path.join(HOME, ".config/hypr/hypridle.conf")
LOCK_CMD = "~/.config/quickshell/lock.sh --fast"
BACKLIGHT = "amdgpu_bl2"

DEFAULTS = {
    "display": {"primary": "DP-1", "side": "right", "wideColor": False,
                "rates": {"eDP-2": 165.02, "DP-1": 200.0}},
    "lock": {"idle": 10, "sleep": False},
    "shell": {"player": True, "playerBg": True, "companions": False},
}


def run(cmd):
    return subprocess.run(cmd, capture_output=True, text=True).stdout.strip()


def load():
    data = json.loads(json.dumps(DEFAULTS))
    try:
        with open(STORE) as f:
            saved = json.load(f)
        for group, values in saved.items():
            if isinstance(values, dict) and group in data:
                data[group].update(values)
    except (OSError, ValueError):
        pass
    return data


def save(data):
    tmp = STORE + ".tmp"
    with open(tmp, "w") as f:
        json.dump(data, f, indent=2)
    os.replace(tmp, STORE)   # atomic, so the shell never reads half a file


def monitors():
    """Connected screens with the refresh rates their current resolution supports."""
    out = []
    for m in json.loads(run(["hyprctl", "monitors", "-j"]) or "[]"):
        res = f"{m['width']}x{m['height']}"
        rates = set()
        for mode in m.get("availableModes", []):
            mm = re.match(r"(\d+x\d+)@([\d.]+)Hz", mode)
            if mm and mm.group(1) == res:
                rates.add(round(float(mm.group(2)), 2))
        out.append({"name": m["name"], "laptop": m["name"].startswith("eDP"),
                    "width": m["width"], "height": m["height"],
                    "rate": round(m["refreshRate"], 2), "rates": sorted(rates, reverse=True)})
    return out


# ── apply: display ──────────────────────────────────────────────────────────

def write_monitors(data):
    d = data["display"]
    mons = monitors()
    laptop = [m for m in mons if m["laptop"]]
    external = [m for m in mons if not m["laptop"]]
    ordered = (laptop + external) if d["side"] == "right" else (external + laptop)
    lines = ["-- Generated by the Control Center (System > Display). Edits here are overwritten;",
             "-- change settings there, or in ~/.config/quickshell/settings/user.json.", ""]
    x = 0
    for m in ordered:
        rate = d["rates"].get(m["name"], m["rates"][0] if m["rates"] else m["rate"])
        mode = f"{m['width']}x{m['height']}@{rate:g}"
        # Wide color gamut off by default: Hyprland enables it on BT.2020-capable screens,
        # which warns (and can band) unless the screen also runs in 10-bit.
        wcg = 1 if d.get("wideColor") else -1
        lines.append(f'hl.monitor({{ output = "{m["name"]}", mode = "{mode}", '
                     f'position = "{x}x0", scale = 1, supports_wide_color = {wcg} }})')
        x += m["width"]
    primary = d["primary"] if any(m["name"] == d["primary"] for m in mons) else \
        (external[0]["name"] if external else (mons[0]["name"] if mons else d["primary"]))
    lines += ["",
              f'hl.workspace_rule({{ workspace = "1", monitor = "{primary}", default = true }})',
              f'hl.config({{ cursor = {{ default_monitor = "{primary}" }} }})', ""]
    with open(MONITORS_LUA, "w") as f:
        f.write("\n".join(lines))
    run(["hyprctl", "reload"])
    errs = run(["hyprctl", "configerrors"])
    if errs:
        print(f"config errors after reload: {errs}", file=sys.stderr)


# ── apply: lock ─────────────────────────────────────────────────────────────

def write_hypridle(data):
    lk = data["lock"]
    conf = ["# Generated by the Control Center (System > Lock & idle).",
            "general {",
            f"    lock_cmd = {LOCK_CMD}   # exits if already locked"]
    if lk["sleep"]:
        conf.append("    before_sleep_cmd = loginctl lock-session")
    conf.append("}")
    if int(lk["idle"]) > 0:
        conf += ["", "listener {",
                 f"    timeout = {int(lk['idle']) * 60}",
                 "    on-timeout = loginctl lock-session", "}"]
    with open(HYPRIDLE, "w") as f:
        f.write("\n".join(conf) + "\n")
    # restart hypridle as a child of Hyprland, not of the shell
    run(["pkill", "-x", "hypridle"])
    run(["hyprctl", "dispatch", 'hl.dsp.exec_cmd("hypridle")'])


# ── state ───────────────────────────────────────────────────────────────────

def state():
    data = load()
    profiles = re.findall(r"^\*?\s*([a-z-]+):", run(["powerprofilesctl", "list"]), re.M)
    try:
        cur = int(run(["brightnessctl", "-d", BACKLIGHT, "get"]))
        mx = int(run(["brightnessctl", "-d", BACKLIGHT, "max"]))
        brightness = round(cur * 100 / mx)
    except ValueError:
        brightness = -1
    data["live"] = {"monitors": monitors(),
                    "profile": run(["powerprofilesctl", "get"]),
                    "profiles": profiles,
                    "brightness": brightness}
    print(json.dumps(data))


def as_bool(v):
    return str(v).lower() in ("1", "true", "yes", "on")


def set_key(key, value):
    data = load()
    if key == "display.primary":
        data["display"]["primary"] = value
        save(data); write_monitors(data)
    elif key == "display.side":
        data["display"]["side"] = "left" if value == "left" else "right"
        save(data); write_monitors(data)
    elif key == "display.wideColor":
        data["display"]["wideColor"] = as_bool(value)
        save(data); write_monitors(data)
    elif key.startswith("display.rate."):
        data["display"]["rates"][key[len("display.rate."):]] = float(value)
        save(data); write_monitors(data)
    elif key == "lock.idle":
        data["lock"]["idle"] = max(0, int(value))
        save(data); write_hypridle(data)
    elif key == "lock.sleep":
        data["lock"]["sleep"] = as_bool(value)
        save(data); write_hypridle(data)
    elif key == "power.profile":
        run(["powerprofilesctl", "set", value])
    elif key == "power.brightness":
        pct = min(100, max(5, int(value)))
        run(["brightnessctl", "-q", "-d", BACKLIGHT, "set", f"{pct}%"])
    elif key.startswith("shell."):
        name = key[len("shell."):]
        if name not in data["shell"]:
            sys.exit(f"unknown key: {key}")
        data["shell"][name] = as_bool(value)
        save(data)
    else:
        sys.exit(f"unknown key: {key}")


if __name__ == "__main__":
    if len(sys.argv) >= 2 and sys.argv[1] == "state":
        state()
    elif len(sys.argv) == 4 and sys.argv[1] == "set":
        set_key(sys.argv[2], sys.argv[3])
    elif len(sys.argv) == 3 and sys.argv[1] == "init":
        # write user.json + monitors.lua from the defaults / current settings
        d = load(); save(d); write_monitors(d)
    else:
        sys.exit(__doc__)
